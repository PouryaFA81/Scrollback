/** Fixtures: app/src/test/resources/office/, generated by scripts/make-office-fixtures.py. */
class OfficeTest {
    @Before fun setUp() { Xml.factory = { KXmlParser() } }

    private fun pkg(name: String): OoxmlPackage {
        val url = javaClass.classLoader!!.getResource("office/$name") ?: error("missing fixture $name")
        return OoxmlPackage(File(url.toURI()))
    }

    @Test fun formatDetection() {
        assertEquals(OfficeFormat.PDF, OfficeFormat.detect("Book.PDF"))
        assertEquals(OfficeFormat.DOCX, OfficeFormat.detect("a.docx"))
        assertEquals(OfficeFormat.TSV, OfficeFormat.detect("a.tsv"))
        assertNull(OfficeFormat.detect("a.doc"))
        assertEquals(OfficeFormat.XLSX, OfficeFormat.fromMime("application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"))
        assertEquals(OfficeFormat.CSV, OfficeFormat.fromMime("text/csv; charset=utf-8"))
    }

    @Test fun resolvePaths() {
        assertEquals("ppt/media/image1.png", OoxmlPackage.resolve("ppt/slides", "../media/image1.png"))
        assertEquals("xl/worksheets/sheet2.xml", OoxmlPackage.resolve("xl", "/xl/worksheets/sheet2.xml"))
        assertEquals("word/media/a.png", OoxmlPackage.resolve("word", "./media/a.png"))
    }

    @Test fun docxMinimal() = pkg("min.docx").use { p ->
        val b = Docx.parse(p).blocks
        val h = b[0] as DocBlock.Paragraph
        assertEquals("Lesson plan", h.text); assertEquals(1, h.heading)
        val runs = (b[1] as DocBlock.Paragraph).runs
        assertEquals("Plain and bold italic", runs.joinToString("") { it.text })
        assertTrue(runs[1].bold); assertFalse(runs[2].bold); assertTrue(runs[2].italic)
        // Two empty paragraphs collapse to one.
        assertEquals("", (b[2] as DocBlock.Paragraph).text)
        assertEquals(ListItem(0, false), (b[3] as DocBlock.Paragraph).list)
        assertEquals(ListItem(1, false), (b[4] as DocBlock.Paragraph).list)
        assertEquals(ListItem(0, true), (b[5] as DocBlock.Paragraph).list)
        assertEquals(listOf(listOf("Name", "Score"), listOf("Sara", "19\n(A)")), (b[6] as DocBlock.Table).rows)
        val loc = b[7] as DocBlock.Paragraph
        assertEquals("Localized heading", loc.text); assertEquals(2, loc.heading)
        assertEquals(8, b.size) // trailing empty paragraph dropped
    }

    @Test fun docxFromLibreOffice() = pkg("lo.docx").use { p ->
        val b = Docx.parse(p).blocks
        val paras = b.filterIsInstance<DocBlock.Paragraph>()
        assertEquals(1, paras.first { it.text == "Office test" }.heading)
        assertEquals(2, paras.first { it.text == "Second" }.heading)
        assertEquals("Hello world.", paras.first { it.text.startsWith("Hello") }.text)
        assertEquals(false, paras.first { it.text == "Apple" }.list?.ordered)
        assertEquals(true, paras.first { it.text == "Two" }.list?.ordered)
        assertEquals(listOf(listOf("a1", "b1"), listOf("a2", "b2")), b.filterIsInstance<DocBlock.Table>().single().rows)
    }

    @Test fun xlsxMinimal() = pkg("min.xlsx").use { p ->
        val wb = Xlsx.parse(p)
        assertEquals(listOf("Grades", "Empty"), wb.sheets.map { it.name })
        val r = wb.sheets[0].rows
        assertEquals(listOf("Name", "Score", "", "Passed"), r[0])
        assertEquals(listOf("Ali", "18", "", "TRUE"), r[1])
        assertEquals(emptyList<String>(), r[2])
        assertEquals(listOf("", "2.5", "5"), r[3])
        assertEquals(4, wb.sheets[0].columns)
        assertTrue(wb.sheets[1].rows.isEmpty())
        assertEquals(27, Xlsx.columnIndex("AB12")); assertEquals(0, Xlsx.columnIndex("A1"))
    }

    @Test fun xlsxFromLibreOffice() = pkg("lo.xlsx").use { p ->
        val rows = Xlsx.parse(p).sheets.first().rows
        assertEquals(listOf("City", "Population"), rows[0])
        assertEquals(listOf("Tehran", "9500000"), rows[1])
        assertEquals(listOf("Shiraz, Fars", "1900000"), rows[2])
    }

    @Test fun pptxMinimal() = pkg("min.pptx").use { p ->
        val s = Pptx.parse(p).slides
        assertEquals(2, s.size)
        assertEquals("Opening", s[0].title) // sldIdLst order, not file order
        assertEquals(listOf("Welcome", "Agenda & goals"), s[0].paragraphs)
        assertEquals("Second in file order", s[1].title)
        assertEquals(listOf("ppt/media/image1.png"), s[1].images)
        assertEquals("Say hello", s[1].notes)
        assertTrue(p.bytes(s[1].images[0])!!.size > 10)
    }

    @Test fun pptxFromLibreOffice() = pkg("lo.pptx").use { p ->
        val s = Pptx.parse(p).slides
        assertEquals(listOf("Intro slide", "Thanks"), s.map { it.title })
        assertEquals(listOf("Point one", "Point two"), s[0].paragraphs)
    }

    @Test(expected = IOException::class) fun wrongPackage() { pkg("min.xlsx").use { Docx.parse(it) } }

    @Test fun csvRoundTrip() {
        val text = "\uFEFFname,note\r\nSara,\"likes \"\"tea\"\", a lot\"\nAli,\"two\nlines\"\n,\n"
        val rows = Csv.parse(text)
        assertEquals(listOf(listOf("name", "note"), listOf("Sara", "likes \"tea\", a lot"), listOf("Ali", "two\nlines"), listOf("", "")), rows)
        assertEquals(rows, Csv.parse(Csv.write(rows)))
        assertEquals(listOf(listOf("a", "b c"), listOf("1", "2")), Csv.parse("a\tb c\n1\t2", '\t'))
        assertEquals(';', Csv.sniff("a;b;c\n1;2;3"))
        assertEquals(',', Csv.sniff("single"))
        assertEquals(listOf(mutableListOf("a", ""), mutableListOf("b", "c")), Csv.rectangular(listOf(listOf("a"), listOf("b", "c"))))
        assertEquals("\" padded\"\n", Csv.write(listOf(listOf(" padded"))))
    }
}
